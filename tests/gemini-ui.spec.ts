import { test, expect } from "@playwright/test";
async function enter(page: import("@playwright/test").Page) {
  await page.goto("./");
  await page.getByRole("button", { name: "Explore the demo" }).click();
  await page.getByRole("button", { name: "Enter demo workspace" }).click();
}
test("Gemini manual and answer are labeled, cited, persisted, and invalidated on source changes", async ({
  page,
}) => {
  const calls: string[] = [];
  await page.route(
    "https://handoff-backend.example/api/generate",
    async (route) => {
      const body = route.request().postDataJSON();
      calls.push(body.mode);
      expect(body.publicDemoDataOnly).toBe(true);
      expect(body.sourceIds).toContain("handbook");
      expect(body).not.toHaveProperty("apiKey");
      const output =
        body.mode === "manual"
          ? {
              sections: ["Who", "What", "When", "Where", "Why", "How"].map(
                (kind) => ({
                  kind,
                  body: "Model-backed sample content.",
                  sourceIds: ["handbook"],
                }),
              ),
            }
          : {
              text: "GitLab is intentional about documenting in a manner that creates a single source of truth.",
              sourceIds: ["handbook"],
              insufficientEvidence: false,
            };
      await route.fulfill({
        json: {
          provider: "gemini",
          model: "mock-model-for-ui-test",
          ...output,
        },
        headers: { "Access-Control-Allow-Origin": "*" },
      });
    },
  );
  await enter(page);
  await page
    .getByRole("button", { name: "Handbook-first working Public handbook topic" })
    .click();
  await page.getByRole("tab", { name: "Knowledge", exact: true }).click();
  await page.getByRole("checkbox", { name: "Use Gemini AI" }).check();
  await page.getByRole("button", { name: "Generate with Gemini" }).click();
  await expect(
    page.getByText(/Generated by Gemini \(mock-model-for-ui-test\)/),
  ).toBeVisible();
  await expect(
    page.getByRole("heading", { name: "How · Getting started" }),
  ).toBeVisible();
  await page
    .getByRole("button", { name: "Handbook-first communication" })
    .first()
    .click();
  await expect(page.getByRole("dialog")).toContainText("single source of truth");
  await page.getByRole("button", { name: "Done reading" }).click();
  await page.getByRole("button", { name: "Approve manual" }).click();
  await page.reload();
  await page.getByRole("button", { name: "Explore the demo" }).click();
  await page.getByRole("button", { name: "Enter demo workspace" }).click();
  await page
    .getByRole("button", { name: "Handbook-first working Public handbook topic" })
    .click();
  await page.getByRole("tab", { name: "Training manual" }).click();
  await expect(page.getByText(/Generated by Gemini/)).toBeVisible();
  await page.getByRole("button", { name: "Ask Handoff", exact: true }).click();
  await page.getByRole("checkbox", { name: "Use Gemini AI" }).check();
  await page
    .getByRole("button", { name: "How does handbook-first communication work?" })
    .click();
  await expect(page.locator(".answer")).toContainText(
    "Gemini · mock-model-for-ui-test",
  );
  await expect(page.locator(".answer")).toContainText("single source of truth");
  await page.getByRole("button", { name: /^Handoffs/ }).click();
  await page.getByRole("tab", { name: "Knowledge", exact: true }).click();
  await page
    .getByRole("checkbox", { name: "Include Handbook-first communication" })
    .uncheck();
  await page.getByRole("tab", { name: "Training manual" }).click();
  await expect(
    page.getByRole("button", { name: "Choose knowledge sources" }),
  ).toBeVisible();
  expect(calls).toEqual(["manual", "answer"]);
});
test("Gemini errors stay errors without simulated fallback", async ({
  page,
}) => {
  await page.route("https://handoff-backend.example/api/generate", (route) =>
    route.fulfill({
      status: 429,
      json: { error: "The shared demo limit has been reached." },
      headers: { "Access-Control-Allow-Origin": "*" },
    }),
  );
  await enter(page);
  await page.getByRole("button", { name: "Ask Handoff", exact: true }).click();
  await page.getByRole("checkbox", { name: "Use Gemini AI" }).check();
  await page
    .getByRole("button", { name: "How does handbook-first communication work?" })
    .click();
  await expect(page.getByRole("alert")).toContainText("shared demo limit");
  await expect(page.locator(".answer")).toHaveCount(0);
  await expect(
    page.getByRole("button", { name: "Send question" }),
  ).toBeDisabled();
});
test("a late answer cannot appear in a different handoff", async ({ page }) => {
  let release!: () => void;
  const gate = new Promise<void>((resolve) => (release = resolve));
  await page.route(
    "https://handoff-backend.example/api/generate",
    async (route) => {
      await gate;
      await route.fulfill({
        json: {
          provider: "gemini",
          model: "mock-model",
          text: "Old handoff response",
          sourceIds: ["handbook"],
          insufficientEvidence: false,
        },
        headers: { "Access-Control-Allow-Origin": "*" },
      });
    },
  );
  await enter(page);
  await page.getByRole("button", { name: "Ask Handoff", exact: true }).click();
  await page.getByRole("checkbox", { name: "Use Gemini AI" }).check();
  await page
    .getByRole("button", { name: "How does handbook-first communication work?" })
    .click();
  await expect(page.getByRole("status")).toContainText("Waiting");
  await page.getByLabel("Knowledge from").selectOption("gitlab-onboarding");
  release();
  await expect(page.getByRole("status")).toHaveCount(0);
  await expect(page.locator(".answer")).toHaveCount(0);
});
